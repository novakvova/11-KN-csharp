using System.Globalization;
using System.Text;

Console.InputEncoding = Encoding.UTF8;
Console.OutputEncoding = Encoding.UTF8;

Console.WriteLine("-- Робота із циклами For --");

//Цикл - дія яка має повторитися
//Можна стоврити змінну, яка буде вказувати кількість повторів
//1 повтор - 1 ітерація циклу.
int n = 5; // Данна змінна визначає кількість повторів у циклі
//Давайте опишемо синтаксис циклу for
//for(ініціалізація_циклу;умова_циклу;лічильник_циклу)
//{ //Початок блоку коду, який працює в циклі
//      код смамого циклу
//} //Кінець циклу

//ініціалізація_циклу; - виконується 1 раз на початку циклу
//умова_циклу; - перевірється кожен раз перед початком ітерації циклу
//лічильник_циклу; - після виконання тіла циклу. Змінює крок ітерації

//int i = 0; - ініціалізація циклу
//i < n; - умова циклу - за якої умови продовжується цикл
//i++; - лічильник циклу
for (int i = 0; i < n; i++)
{
    Console.WriteLine("Слава Україні :)");
}

//Задача
//Програма запитує, як звати користувача
//Програма запитує скількільки разів з Вами привітатися.
//Зробити цикл, який виводить привітання
Console.WriteLine("Як Вас звати");
Console.Write("->_");
string name = Console.ReadLine(); //Запитую слова у користвача
Console.WriteLine("Скільки разів Вас привітати");
Console.Write("->_");
int count = int.Parse(Console.ReadLine()); //читає число від користувача
for (int i = 0; i < count; i++)
{
    Console.WriteLine("Вітаємо Вас дружок "+ name+". Добре їсти добре спати :)");
}
